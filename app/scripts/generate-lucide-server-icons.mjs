#!/usr/bin/env node
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = resolve(root, "apps/desktop/node_modules/lucide-react");
const packageJson = JSON.parse(await readFile(resolve(packageDir, "package.json"), "utf8"));
const { default: imports } = await import(resolve(packageDir, "dynamicIconImports.mjs"));
const outputPath = resolve(root, "apps/server/src/render/lucide-icons.generated.ts");
const check = process.argv.includes("--check");

const ALLOWED_TAGS = new Set(["circle", "ellipse", "line", "path", "polygon", "polyline", "rect"]);
const ALLOWED_ATTRIBUTES = new Set([
  "cx", "cy", "d", "fill", "height", "points", "r", "rx", "ry", "width",
  "x", "x1", "x2", "y", "y1", "y2",
]);

const nodes = {};
const aliases = {};
for (const id of Object.keys(imports).sort()) {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(id)) throw new Error(`Unsafe Lucide id: ${id}`);
  const loaded = await imports[id]();
  const icon = loaded.__iconData;
  if (!icon || !Array.isArray(icon.node) || typeof icon.name !== "string") {
    throw new Error(`Missing Lucide icon data: ${id}`);
  }
  const safeNodes = icon.node.map(([tag, attributes]) => {
    if (!ALLOWED_TAGS.has(tag)) throw new Error(`Unsupported Lucide tag ${tag} in ${id}`);
    const safeAttributes = {};
    for (const [name, value] of Object.entries(attributes)) {
      if (name === "key") continue;
      if (!ALLOWED_ATTRIBUTES.has(name)) {
        throw new Error(`Unsupported Lucide attribute ${name} in ${id}`);
      }
      if (name === "fill" && value !== "currentColor") {
        throw new Error(`Unsupported Lucide fill ${String(value)} in ${id}`);
      }
      if (typeof value !== "string" && typeof value !== "number") {
        throw new Error(`Unsupported Lucide value for ${name} in ${id}`);
      }
      safeAttributes[name] = value;
    }
    return [tag, safeAttributes];
  });
  nodes[icon.name] ??= safeNodes;
  if (id !== icon.name) aliases[id] = icon.name;
}

const source = `/* eslint-disable */
// GENERATED by scripts/generate-lucide-server-icons.mjs from lucide-react ${packageJson.version}.
// Do not edit by hand. License: ../../THIRD_PARTY_NOTICES/Lucide-LICENSE.txt
export type LucideNode = readonly [
  tag: "circle" | "ellipse" | "line" | "path" | "polygon" | "polyline" | "rect",
  attributes: Readonly<Record<string, string | number>>,
];

export const LUCIDE_NODES: Readonly<Record<string, readonly LucideNode[]>> = ${JSON.stringify(nodes)};

export const LUCIDE_ALIASES: Readonly<Record<string, string>> = ${JSON.stringify(aliases)};

export const LUCIDE_ICON_IDS = ${JSON.stringify(Object.keys(imports).sort())} as const;
`;

if (check) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== source) {
    console.error("Generated Lucide server registry is stale. Run: pnpm generate:lucide-server-icons");
    process.exit(1);
  }
  console.log(`Lucide server registry is current (${Object.keys(imports).length} ids).`);
} else {
  await writeFile(outputPath, source);
  console.log(`Wrote ${outputPath} (${Object.keys(imports).length} ids).`);
}
